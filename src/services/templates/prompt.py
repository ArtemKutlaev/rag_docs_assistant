def get_prompt(context:str,query:str) -> str:
    """
    Формирует промпт для RAG-системы, объединяя контекст из книги и вопрос пользователя.

    Args:
        context (str): Найденные фрагменты текста из книги (выданные функцией поиска).
        query (str): Вопрос пользователя.

    Returns:
        str: Готовый промпт для отправки в LLM.
    """
    
    prompt = f"""Ты — профессиональный технический ассистент и преподаватель по машинному обучению.
    Твоя задача — отвечать на вопросы пользователя ПОДРОБНО, развернуто и понятно, опираясь СТРОГО на предоставленный контекст из книги Себастьяна Рашки.
    Если в контексте есть формула, объяснение или пример — обязательно включи их в ответ. Объясняй так, чтобы студент мог полностью понять суть термина.
    
    Контекст из книги:
    ---------------------
    {context}
    ---------------------

    Вопрос пользователя: {query}
    """
    return prompt